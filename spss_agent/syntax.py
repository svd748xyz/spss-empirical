"""Build one SPSS syntax file and per-block OMS destinations from a confirmed plan."""

from __future__ import annotations

from pathlib import Path

from spss_agent.plan import mediator_names, moderator_names
from spss_agent.prepare import infer_formats


def _q(path: Path | str) -> str:
    text = str(path).replace("\\", "/")
    if "'" in text:
        raise ValueError(f"路径含单引号，SPSS 语法无法安全引用：{text}")
    return f"'{text}'"


def _vars(names: list[str]) -> str:
    return " ".join(names)


def _lab(text: str) -> str:
    return str(text).replace("'", "''")


class SyntaxJob:
    def __init__(self, oms_dir: Path):
        self.oms_dir = oms_dir
        self.lines: list[str] = [
            "SET UNICODE=ON.",
            "SET OLANG=ENGLISH.",
            "SET TVARS=NAMES TNUMBERS=LABELS.",
            "* Generated by spss_agent. Do not edit by hand if you need a reproducible rerun.",
        ]
        self.blocks: list[dict] = []

    def add(self, text: str) -> None:
        self.lines.append(text.rstrip())

    def block(self, block_id: str, kind: str, meta: dict, body: str) -> None:
        outfile = self.oms_dir / f"{block_id}.xml"
        self.blocks.append({"id": block_id, "kind": kind, "meta": meta, "oms": str(outfile)})
        self.add(
            "OMS\n"
            "  /SELECT ALL\n"
            f"  /DESTINATION FORMAT=OXML OUTFILE={_q(outfile)}."
        )
        self.add(body.rstrip())
        self.add("OMSEND.")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def _regression_body(dependent: str, blocks: list[list[str]]) -> str:
    methods = "\n".join(f"  /METHOD=ENTER {_vars(block)}" for block in blocks)
    return (
        "REGRESSION\n"
        "  /MISSING LISTWISE\n"
        "  /STATISTICS COEFF OUTS R ANOVA COLLIN TOL CHANGE\n"
        f"  /DEPENDENT {dependent}\n"
        f"{methods}."
    )


def build_syntax(plan: dict, data_csv: Path | None, formats: list[tuple[str, str]] | None, oms_dir: Path) -> SyntaxJob:
    job = SyntaxJob(oms_dir)
    data_file = Path(plan["data_file"])
    if data_file.suffix.lower() == ".sav":
        job.add(f"GET FILE={_q(data_file)}.")
    else:
        if data_csv is None or formats is None:
            raise ValueError("Excel/CSV 需要先整理为 SPSS 可读的 CSV。")
        variable_lines = "\n".join(f"    {name} {fmt}" for name, fmt in formats)
        job.add(
            "GET DATA\n"
            "  /TYPE=TXT\n"
            f"  /FILE={_q(data_csv)}\n"
            "  /ENCODING='UTF8'\n"
            "  /DELCASE=LINE\n"
            '  /DELIMITERS=","\n'
            "  /QUALIFIER='\"'\n"
            "  /ARRANGEMENT=DELIMITED\n"
            "  /FIRSTCASE=2\n"
            "  /IMPORTCASE=ALL\n"
            "  /VARIABLES=\n"
            f"{variable_lines}."
        )
    job.add("DATASET NAME source.")
    job.add("DATASET ACTIVATE source.")

    labels = []
    computed = False
    for scale in plan.get("scales") or []:
        for rev in scale.get("reverse") or []:
            computed = True
            job.add(f"COMPUTE {rev['name']}={rev['low']}+{rev['high']}-{rev['item']}.")
        items = ",".join(scale["items"])
        target = scale["name"]
        computed = True
        job.add(f"COMPUTE {target}=MEAN({items}).")
        label = scale.get("label") or target
        labels.append(f"  {target} '{_lab(label)}'")
    for variable in plan.get("variables") or []:
        for dummy in variable.get("dummies") or []:
            computed = True
            job.add(f"COMPUTE {dummy['name']}=({variable['name']} = {dummy['code']}).")
    if computed:
        job.add("EXECUTE.")
    for variable in plan.get("variables") or []:
        if variable.get("label"):
            labels.append(f"  {variable['name']} '{_lab(variable['label'])}'")
    if labels:
        job.add("VARIABLE LABELS\n" + "\n".join(labels) + ".")
    value_chunks = []
    for variable in plan.get("variables") or []:
        values = variable.get("values") or {}
        if not values:
            continue
        pairs = " ".join(f"{code} '{_lab(label)}'" for code, label in values.items())
        value_chunks.append(f"  {variable['name']} {pairs}")
    if value_chunks:
        job.add("VALUE LABELS\n" + "\n".join(value_chunks) + ".")

    for index, raw in enumerate(plan.get("analyses") or [], start=1):
        analysis = {**raw, "analysis_index": index}
        kind = analysis["type"]
        block_id = f"{index:02d}_{kind}"
        if kind == "descriptives":
            variables = analysis["vars"]
            job.block(
                block_id,
                kind,
                analysis,
                "DESCRIPTIVES VARIABLES="
                + _vars(variables)
                + "\n  /STATISTICS=MEAN STDDEV MIN MAX.",
            )
        elif kind == "frequencies":
            job.block(
                block_id,
                kind,
                analysis,
                "FREQUENCIES VARIABLES=" + _vars(analysis["vars"]) + "\n  /ORDER=ANALYSIS.",
            )
        elif kind == "reliability":
            items = analysis["items"]
            job.block(
                block_id,
                kind,
                analysis,
                "RELIABILITY\n"
                f"  /VARIABLES={_vars(items)}\n"
                f"  /SCALE({analysis.get('scale', 'scale')}) ALL\n"
                "  /MODEL=ALPHA\n"
                "  /STATISTICS=DESCRIPTIVE SCALE\n"
                "  /SUMMARY=TOTAL.",
            )
        elif kind == "zscreen":
            dummy = f"dscr{index}"
            aggregate = [f"COMPUTE {dummy}=1.", "AGGREGATE", "  /OUTFILE=* MODE=ADDVARIABLES", f"  /BREAK={dummy}"]
            flags = []
            for offset, variable in enumerate(analysis["vars"], start=1):
                mean_name = f"zm{index}_{offset}"
                sd_name = f"zs{index}_{offset}"
                flag = f"zo{index}_{offset}"
                aggregate.append(f"  /{mean_name}=MEAN({variable})")
                aggregate.append(f"  /{sd_name}=SD({variable})")
                flags.append((variable, flag, mean_name, sd_name))
            job.add("\n".join(aggregate) + ".")
            for variable, flag, mean_name, sd_name in flags:
                job.add(f"COMPUTE {flag}=ABS(({variable}-{mean_name})/{sd_name})>3.")
            job.add("EXECUTE.")
            job.block(
                block_id,
                kind,
                {**analysis, "flags": [{"var": variable, "flag": flag} for variable, flag, _, _ in flags]},
                "DESCRIPTIVES VARIABLES=" + _vars([flag for _, flag, _, _ in flags]) + "\n  /STATISTICS=MEAN STDDEV MIN MAX.",
            )
        elif kind == "harman":
            items = analysis["items"]
            job.block(
                block_id,
                kind,
                analysis,
                "FACTOR\n"
                f"  /VARIABLES {_vars(items)}\n"
                "  /MISSING LISTWISE\n"
                f"  /ANALYSIS {_vars(items)}\n"
                "  /PRINT INITIAL EXTRACTION KMO\n"
                "  /CRITERIA MINEIGEN(1) ITERATE(25)\n"
                "  /EXTRACTION PC\n"
                "  /ROTATION NOROTATE\n"
                "  /METHOD=CORRELATION.",
            )
        elif kind == "efa":
            items = analysis["items"]
            job.block(
                block_id,
                kind,
                analysis,
                "FACTOR\n"
                f"  /VARIABLES {_vars(items)}\n"
                "  /MISSING LISTWISE\n"
                f"  /ANALYSIS {_vars(items)}\n"
                "  /PRINT INITIAL KMO EXTRACTION ROTATION\n"
                "  /CRITERIA MINEIGEN(1) ITERATE(25)\n"
                "  /EXTRACTION PC\n"
                "  /ROTATION VARIMAX\n"
                "  /METHOD=CORRELATION.",
            )
        elif kind == "correlation":
            job.block(
                block_id,
                kind,
                analysis,
                "CORRELATIONS\n"
                f"  /VARIABLES={_vars(analysis['vars'])}\n"
                "  /PRINT=TWOTAIL NOSIG\n"
                "  /MISSING=PAIRWISE.",
            )
        elif kind == "ttest":
            group = analysis["group"]
            codes = analysis.get("codes") or [1, 2]
            job.block(
                block_id,
                kind,
                analysis,
                "T-TEST\n"
                f"  /GROUPS={group}({codes[0]} {codes[1]})\n"
                f"  /VARIABLES={_vars(analysis['outcomes'])}\n"
                "  /CRITERIA=CI(.95).",
            )
        elif kind == "anova":
            job.block(
                block_id,
                kind,
                analysis,
                "ONEWAY " + _vars(analysis["outcomes"]) + f" BY {analysis['factor']}\n"
                "  /STATISTICS DESCRIPTIVES HOMOGENEITY\n"
                "  /POSTHOC=BONFERRONI ALPHA(0.05)\n"
                "  /MISSING ANALYSIS.",
            )
        elif kind == "regression":
            job.block(block_id, kind, analysis, _regression_body(analysis["dependent"], analysis["blocks"]))
        elif kind == "mediation":
            controls = analysis.get("controls") or []
            x, y = analysis["x"], analysis["y"]
            mediators = mediator_names(analysis)
            structure = analysis.get("structure") or "parallel"
            for offset, mediator in enumerate(mediators, start=1):
                step_id = f"{block_id}_a" if len(mediators) == 1 else f"{block_id}_a{offset}"
                predictors = [x, *mediators[: offset - 1], *controls] if structure == "serial" else [x, *controls]
                job.block(
                    step_id,
                    "regression",
                    {**analysis, "step": "a", "mediator": mediator},
                    _regression_body(mediator, [predictors]),
                )
            job.block(f"{block_id}_c", "regression", {**analysis, "step": "c"}, _regression_body(y, [[x, *controls]]))
            job.block(
                f"{block_id}_b",
                "regression",
                {**analysis, "step": "b", "mediators": mediators},
                _regression_body(y, [[x, *mediators, *controls]]),
            )
        elif kind == "spearman":
            job.block(
                block_id,
                kind,
                analysis,
                "NONPAR CORR\n"
                f"  /VARIABLES={_vars(analysis['vars'])}\n"
                "  /PRINT=SPEARMAN TWOTAIL NOSIG\n"
                "  /MISSING=PAIRWISE.",
            )
        elif kind == "chisq":
            job.block(
                block_id,
                kind,
                analysis,
                f"CROSSTABS\n  /TABLES={analysis['row']} BY {analysis['col']}\n  /STATISTICS=CHISQ\n  /CELLS=COUNT.",
            )
        elif kind == "mannwhitney":
            group = analysis["group"]
            codes = analysis.get("codes") or [1, 2]
            job.block(
                block_id,
                kind,
                analysis,
                "NPAR TESTS\n"
                f"  /M-W={_vars(analysis['outcomes'])} BY {group}({codes[0]} {codes[1]}).",
            )
        elif kind == "kruskal":
            codes = analysis["codes"]
            job.block(
                block_id,
                kind,
                analysis,
                "NPAR TESTS\n"
                f"  /K-W={_vars(analysis['outcomes'])} BY {analysis['factor']}({codes[0]} {codes[1]}).",
            )
        elif kind == "logistic":
            job.block(
                block_id,
                kind,
                analysis,
                "LOGISTIC REGRESSION " + analysis["dependent"] + "\n"
                f"  WITH {_vars(analysis['predictors'])}\n"
                "  /METHOD=ENTER.",
            )
        elif kind == "moderated_mediation":
            _add_moderated_mediation(job, analysis, index, block_id)
        elif kind == "moderation" and isinstance(analysis.get("w"), list):
            _add_multiple_moderation(job, analysis, index, block_id)
        elif kind == "moderation":
            x, w, y = analysis["x"], analysis["w"], analysis["y"]
            controls = analysis.get("controls") or []
            dummy = f"d_{index}"
            xc, wc, xw = f"{x}_c", f"{w}_c", f"xw_{index}"
            wh, wl = f"w_hi_{index}", f"w_lo_{index}"
            xwh, xwl = f"xwh_{index}", f"xwl_{index}"
            job.add(f"COMPUTE {dummy}=1.")
            job.add(
                "AGGREGATE\n"
                "  /OUTFILE=* MODE=ADDVARIABLES\n"
                f"  /BREAK={dummy}\n"
                f"  /{x}_m=MEAN({x})\n"
                f"  /{w}_m=MEAN({w})\n"
                f"  /{w}_sd=SD({w})."
            )
            job.add(f"COMPUTE {xc}={x}-{x}_m.")
            job.add(f"COMPUTE {wc}={w}-{w}_m.")
            job.add(f"COMPUTE {xw}={xc}*{wc}.")
            job.add(f"COMPUTE {wh}={wc}-{w}_sd.")
            job.add(f"COMPUTE {wl}={wc}+{w}_sd.")
            job.add(f"COMPUTE {xwh}={xc}*{wh}.")
            job.add(f"COMPUTE {xwl}={xc}*{wl}.")
            job.add("EXECUTE.")
            base = [xc, wc, *controls]
            job.block(f"{block_id}_main", "regression", {**analysis, "step": "main", "x_c": xc, "w_c": wc, "xw": xw}, _regression_body(y, [base, [*base, xw]]))
            job.block(
                f"{block_id}_high",
                "regression",
                {**analysis, "step": "high", "slope_var": xc},
                _regression_body(y, [[xc, wh, xwh, *controls]]),
            )
            job.block(
                f"{block_id}_low",
                "regression",
                {**analysis, "step": "low", "slope_var": xc},
                _regression_body(y, [[xc, wl, xwl, *controls]]),
            )
        else:
            raise ValueError(f"分析方案含未实现的类型：{kind}")
    return job


def _add_multiple_moderation(job: SyntaxJob, analysis: dict, index: int, block_id: str) -> None:
    x, y = analysis["x"], analysis["y"]
    moderators = moderator_names(analysis)
    controls = analysis.get("controls") or []
    dummy = f"d_{index}"
    xc = f"xc_{index}"
    specs = []
    aggregate = [
        f"COMPUTE {dummy}=1.",
        "AGGREGATE",
        "  /OUTFILE=* MODE=ADDVARIABLES",
        f"  /BREAK={dummy}",
        f"  /xm_{index}=MEAN({x})",
    ]
    for offset, moderator in enumerate(moderators):
        aggregate.append(f"  /wm_{index}_{offset}=MEAN({moderator})")
        aggregate.append(f"  /ws_{index}_{offset}=SD({moderator})")
    job.add("\n".join(aggregate) + ".")
    job.add(f"COMPUTE {xc}={x}-xm_{index}.")
    for offset, moderator in enumerate(moderators):
        wc = f"wc_{index}_{offset}"
        xw = f"xw_{index}_{offset}"
        wh = f"wh_{index}_{offset}"
        wl = f"wl_{index}_{offset}"
        xwh = f"xwh_{index}_{offset}"
        xwl = f"xwl_{index}_{offset}"
        job.add(f"COMPUTE {wc}={moderator}-wm_{index}_{offset}.")
        job.add(f"COMPUTE {xw}={xc}*{wc}.")
        job.add(f"COMPUTE {wh}={wc}-ws_{index}_{offset}.")
        job.add(f"COMPUTE {wl}={wc}+ws_{index}_{offset}.")
        job.add(f"COMPUTE {xwh}={xc}*{wh}.")
        job.add(f"COMPUTE {xwl}={xc}*{wl}.")
        specs.append({"name": moderator, "w_c": wc, "xw": xw, "wh": wh, "wl": wl, "xwh": xwh, "xwl": xwl})
    job.add("EXECUTE.")
    base = [xc, *[item["w_c"] for item in specs], *controls]
    interactions = [item["xw"] for item in specs]
    job.block(
        f"{block_id}_main",
        "regression",
        {**analysis, "step": "main", "x_c": xc, "moderators": [{"name": item["name"], "w_c": item["w_c"], "xw": item["xw"]} for item in specs]},
        _regression_body(y, [base, [*base, *interactions]]),
    )
    for offset, item in enumerate(specs):
        high = [xc]
        low = [xc]
        for other in specs:
            if other is item:
                high.extend([item["wh"], item["xwh"]])
                low.extend([item["wl"], item["xwl"]])
            else:
                high.extend([other["w_c"], other["xw"]])
                low.extend([other["w_c"], other["xw"]])
        shared = {**analysis, "moderator": item["name"], "slope_var": xc, "interaction": item["xw"]}
        job.block(f"{block_id}_high_{offset}", "regression", {**shared, "step": f"high_{offset}"}, _regression_body(y, [[*high, *controls]]))
        job.block(f"{block_id}_low_{offset}", "regression", {**shared, "step": f"low_{offset}"}, _regression_body(y, [[*low, *controls]]))


def _center(job: SyntaxJob, index: int, x: str | None, m: str | None, w: str) -> dict:
    dummy = f"dmm_{index}"
    names = {"w": w, "wc": f"mmw_{index}", "wh": f"mmwh_{index}", "wl": f"mmwl_{index}"}
    aggregate = [f"COMPUTE {dummy}=1.", "AGGREGATE", "  /OUTFILE=* MODE=ADDVARIABLES", f"  /BREAK={dummy}", f"  /mmwm_{index}=MEAN({w})", f"  /mmws_{index}=SD({w})"]
    if x:
        aggregate.append(f"  /mmxm_{index}=MEAN({x})")
        names["x"] = x
        names["xc"] = f"mmx_{index}"
    if m:
        aggregate.append(f"  /mmmm_{index}=MEAN({m})")
        names["m"] = m
        names["mc"] = f"mmm_{index}"
    job.add("\n".join(aggregate) + ".")
    job.add(f"COMPUTE {names['wc']}={w}-mmwm_{index}.")
    job.add(f"COMPUTE {names['wh']}={names['wc']}-mmws_{index}.")
    job.add(f"COMPUTE {names['wl']}={names['wc']}+mmws_{index}.")
    if x:
        names["xw"] = f"mmxw_{index}"
        names["xwh"] = f"mmxwh_{index}"
        names["xwl"] = f"mmxwl_{index}"
        job.add(f"COMPUTE {names['xc']}={x}-mmxm_{index}.")
        job.add(f"COMPUTE {names['xw']}={names['xc']}*{names['wc']}.")
        job.add(f"COMPUTE {names['xwh']}={names['xc']}*{names['wh']}.")
        job.add(f"COMPUTE {names['xwl']}={names['xc']}*{names['wl']}.")
    if m:
        names["mw"] = f"mmmw_{index}"
        names["mwh"] = f"mmmwh_{index}"
        names["mwl"] = f"mmmwl_{index}"
        job.add(f"COMPUTE {names['mc']}={m}-mmmm_{index}.")
        job.add(f"COMPUTE {names['mw']}={names['mc']}*{names['wc']}.")
        job.add(f"COMPUTE {names['mwh']}={names['mc']}*{names['wh']}.")
        job.add(f"COMPUTE {names['mwl']}={names['mc']}*{names['wl']}.")
    job.add("EXECUTE.")
    return names


def _add_moderated_mediation(job: SyntaxJob, analysis: dict, index: int, block_id: str) -> None:
    x, m, y, w = analysis["x"], analysis["m"], analysis["y"], analysis["w"]
    controls = analysis.get("controls") or []
    stage = analysis["stage"]
    centered = _center(job, index, x if stage in {"a", "both"} else None, m if stage in {"b", "both"} else None, w)
    if stage in {"a", "both"}:
        xc, wc, xw = centered["xc"], centered["wc"], centered["xw"]
        shared = {"slope_var": xc, "interaction": xw}
        job.block(
            f"{block_id}_a_main",
            "regression",
            {**analysis, **shared, "step": "a_main"},
            _regression_body(m, [[xc, wc, xw, *controls]]),
        )
        job.block(
            f"{block_id}_a_high",
            "regression",
            {**analysis, **shared, "step": "a_high"},
            _regression_body(m, [[xc, centered["wh"], centered["xwh"], *controls]]),
        )
        job.block(
            f"{block_id}_a_low",
            "regression",
            {**analysis, **shared, "step": "a_low"},
            _regression_body(m, [[xc, centered["wl"], centered["xwl"], *controls]]),
        )
    else:
        job.block(f"{block_id}_a", "regression", {**analysis, "step": "a"}, _regression_body(m, [[x, *controls]]))
    if stage == "a":
        job.block(f"{block_id}_b", "regression", {**analysis, "step": "b"}, _regression_body(y, [[x, m, w, *controls]]))
    else:
        mc, wc, mw = centered["mc"], centered["wc"], centered["mw"]
        shared_b = {"slope_var": mc, "interaction": mw}
        job.block(
            f"{block_id}_b_main",
            "regression",
            {**analysis, **shared_b, "step": "b_main"},
            _regression_body(y, [[x, mc, wc, mw, *controls]]),
        )
        job.block(
            f"{block_id}_b_high",
            "regression",
            {**analysis, **shared_b, "step": "b_high"},
            _regression_body(y, [[x, mc, centered["wh"], centered["mwh"], *controls]]),
        )
        job.block(
            f"{block_id}_b_low",
            "regression",
            {**analysis, **shared_b, "step": "b_low"},
            _regression_body(y, [[x, mc, centered["wl"], centered["mwl"], *controls]]),
        )
    job.block(f"{block_id}_c", "regression", {**analysis, "step": "c"}, _regression_body(y, [[x, *controls]]))


def formats_for(frame) -> list[tuple[str, str]]:
    return infer_formats(frame)
